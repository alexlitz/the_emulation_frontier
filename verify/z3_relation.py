def differential_real(space, P, modes=CODE_MODES, flags=((False, False), (True, True)), z3_sample=100,
                      seed=0, log=print, J=None):
    """Model vs emul_matrix on every ordered pair of the real shapes (and the joined host J as a host column).
    Returns the total number of disagreements."""
    total_bad = 0
    for ctx, vocab in flags:
        with _Flags(ctx, vocab):
            model = Model(space, ctx, vocab, ROPE_K_DIFF, FW_K_DIFF)
            ev = Evaluator(model)
            for mode in modes:
                t0 = time.time()
                real = G.emul_matrix(P, mode=mode)
                mine = ev.matrix(P, mode)
                bad = np.argwhere(real != mine)
                total_bad += len(bad)
                log(f"  real pairs  ctx={ctx!s:5} vocab={vocab!s:5} {mode:8s}: {real.size:,} pairs, "
                    f"{real.sum():,} edges, {len(bad)} disagreements ({time.time() - t0:.0f}s)")
                for i, j in bad[:5]:
                    log(f"      DISAGREE target {_name(P[i])} host {_name(P[j])}: code {real[i, j]} model {mine[i, j]}")
                if J is not None:
                    PJ = list(P) + [J]
                    rj = G.emul_matrix(PJ, mode=mode)[:-1, -1]
                    mj = ev.matrix(PJ, mode)[:-1, -1]
                    nb = int((rj != mj).sum())
                    total_bad += nb
                    log(f"      joined host as host: {int(rj.sum())} / {len(P)} hosted, {nb} disagreements")
                    for i in np.flatnonzero(rj != mj)[:5]:
                        log(f"      DISAGREE target {_name(P[i])} host JOIN: code {rj[i]} model {mj[i]}")
                # the interpreter itself, against Z3's own simplifier on a sample of pairs
                rng = np.random.default_rng(seed)
                e = ev.expr(mode)
                yes, no = np.argwhere(real & ~np.eye(len(P), dtype=bool)), np.argwhere(~real)
                n_s = z3_sample if mode == "payable" and not ctx else max(z3_sample // 10, 2)
                picks = [yes[x] for x in rng.integers(len(yes), size=n_s // 2)] if len(yes) else []
                picks += [no[x] for x in rng.integers(len(no), size=n_s - len(picks))] if len(no) else []
                for i, j in picks:
                    if i == j:
                        continue
                    subs = []
                    for nm, p in (("T", P[i]), ("H", P[j])):
                        for k, v in point_values(model, p).items():
                            subs.append((z3.Bool(f"{nm}.{k}"), z3.BoolVal(v)) if isinstance(v, (bool, np.bool_))
                                        else (z3.Int(f"{nm}.{k}"), z3.IntVal(int(v))))
                    zv = z3.is_true(z3.simplify(z3.substitute(e, *subs)))
                    if zv != bool(mine[i, j]):
                        total_bad += 1
                        log(f"      INTERPRETER MISMATCH at ({i}, {j}): z3 {zv}, numpy {mine[i, j]}")
    return total_bad


def point_strategy(space, max_dim=6, rope_k=ROPE_K_DIFF, fw_k=4):
    """Synthetic emul_matrix points over the whole value space: every slot value (tops, branch sets, sentinels),
    any feature subset, tiny dims (ties), any rope tuples (NoPE slots included), MoE signatures, recurrent dims,
    per-layer FFN widths."""
    from hypothesis import strategies as st
    S = space
    small = st.integers(0, max_dim)
    slots = st.fixed_dictionaries({s: st.sampled_from(S.vals[s]) for s in ALL_SLOTS})
    feats = st.lists(st.sampled_from([f for f in S.feats if f != "rf_*"]), max_size=4, unique=True)
    rope = st.lists(st.integers(-4, 6), max_size=rope_k)
    ints = {k: small for k in BASE_DIMS + KIND_DIMS + CTX_DIMS + VOCAB_DIMS}
    ints["rc_rule"] = st.integers(0, 5)
    ints["rc_free"] = st.sampled_from([0, 0, 0, 1])
    ints["alibi_max"] = st.sampled_from([0, 8])
    ints["alibi_bf16"] = st.integers(0, 1)
    ints["alibi_heads"] = st.integers(0, 12)
    ints["alibi_sinv"] = st.sampled_from([0] + list(S.alibi_sinvs))          # (round 3: the Falcon slope scale)
    for k in ("mla_qswitch", "mla_lat_free", "rope_pairs_free", "moe_unit_top1", "alibi_off") + P5_INT:
        ints[k] = st.integers(0, 1)
    ints["pos_table"] = st.integers(0, 6)
    if G._r3("max_context_unknown"):                                         # (round 3: the context codes)
        for k in CTX_CODED:
            ints[k] = st.one_of(small, st.sampled_from([G.CTX_UNKNOWN, G.CTX_UNBOUNDED]))
    ints["bias_up"] = st.integers(0, 1)                                      # (round 3, batch 3b)
    ints["rope_lin"] = st.integers(0, 2 if G._r3("nope_rope_limit") else 0)  # (round 3, nope_rope_limit)
    ints["hada_n"] = st.sampled_from([0, 0, 0, 2, 4])
    ints["bias_shift"] = st.sampled_from([0, 0, 0, 1])                       # (round 3, batch 4b)
    ints["readout_bias"] = st.sampled_from([0, 0, 1])                         # (round 3, nonlm_heads)
    dims = st.fixed_dictionaries(ints)
    fw = st.one_of(st.just(()), st.lists(st.integers(1, 6), min_size=1, max_size=6).map(
        lambda v: tuple(sorted(v, reverse=True))).filter(lambda v: len(set(v)) <= fw_k))

    @st.composite
    def sig(draw):
        if draw(st.integers(0, 5)) == 0:
            return None
        E = draw(st.sampled_from([0, 0, 1, 2, 3, 4, 6, 8]))
        k = draw(st.integers(1, 4)) if E else 0
        ren = draw(st.sampled_from(S.renorm_vals)) if E else ""
        rcap = tuple(sorted(set(draw(st.lists(st.sampled_from(S.renorm_vals), max_size=2))) | {ren})) if E else ()
        sc = draw(st.sampled_from([v for v in S.score_vals if v])) if E else ""
        scap = tuple(sorted(set(draw(st.lists(st.sampled_from(S.score_vals), max_size=2))) | {sc})) if E else ()
        ng = draw(st.sampled_from([0, 0, 2, 4])) if E else 0
        gc = draw(st.sampled_from(S.gcap_vals)) if E else ""
        base = (E, k, draw(small), draw(small), ren, rcap, sc, scap, ng, draw(small) if ng else 0, gc,
                draw(small), draw(small), draw(small), draw(st.sampled_from([0, 0, 2, 5])), draw(st.integers(0, 1)))
        if not E:                                    # (round 3, batch 3a: the MoE-block forms G.MOE_SIG_R3)
            return base + G.MOE_SIG_R3_DENSE
        blk = draw(st.sampled_from([0, 0, 0, 2]))
        return base + (draw(st.sampled_from([0, 0, 1])), draw(st.sampled_from(S.lnorm_vals)),
                       draw(st.sampled_from([0, 0, 1, 2])), blk, draw(st.sampled_from([2, 3])) if blk else 0,
                       draw(st.sampled_from([0, 0, 0, 3])))

    # (round 3, batch 2d: a shape's V width, and the per-shape layer counts kv_shape_n -- absent: spread evenly)
    shape4 = st.tuples(st.integers(0, 4), st.integers(0, 4), st.integers(0, 6), st.integers(0, 6))
    shapes = st.one_of(st.just(((), ())), st.lists(shape4, min_size=1, max_size=KV_SHAPES).flatmap(
        lambda sh: st.tuples(st.just(tuple(sh)), st.one_of(st.just(()), st.lists(
            st.integers(0, 6), min_size=len(sh), max_size=len(sh)).map(tuple)))))
    extra = st.tuples(st.sampled_from(S.kind_vals), shapes,
                      st.sampled_from(S.r3_vals["emb_norm"]), st.sampled_from(S.r3_vals["gnorm_sites"]),
                      st.sampled_from(S.r3_vals["canon"]),
                      *[st.sampled_from([v for v in S.r3_vals[k] if "|" not in v and v != "*"]) for k in R3_SIGS],
                      st.sampled_from(["", "", ""] + list(KO_SYNTH)))         # (round 3, kind_order)

    def build(s, f, d, rs, rc, w, sg, ex):
        sl = dict(s)
        sl["feats"] = "+".join(f)
        dd = dict(d)
        dd["rope_sched"] = tuple(rs)
        dd["rope_cap"] = tuple(rc)
        dd["ffn_widths"] = w
        if sg is not None:
            dd["moe_sig"] = sg
        dd["rope_kind"] = ex[0]
        if ex[1][0]:
            dd["kv_shapes"] = tuple(ex[1][0])
            if ex[1][1]:
                dd["kv_shape_n"] = tuple(ex[1][1])
        dd["emb_norm"], dd["gnorm_sites"] = ex[2], ex[3]                 # round 3, batch 1
        dd["canon"] = ex[4]                                              # round 3, batch 2d
        for k, v in zip(R3_SIGS, ex[5:5 + len(R3_SIGS)]):                # round 3, batch 4b
            dd[k] = v
        dd["kseq"] = ex[5 + len(R3_SIGS)]                                 # round 3, kind_order
        sv = dd.pop("alibi_sinv", 0)                                     # round 3, batch 2b: dims_of's float scale
        dd["alibi_scale"] = 1.0 / sv ** 0.5 if sv else 0.0
        return {"slots": sl, "dims": dd}
    return st.builds(build, slots, feats, dims, rope, rope, fw, sig(), extra)


def point_lists(space, max_size=12):
    """Lists of synthetic points where most points are MUTANTS of a few base points (a few slots, features and
    dims moved, mostly upward): near-equal pairs, so edges and the boundaries between edge and non-edge occur."""
    from hypothesis import strategies as st
    base = point_strategy(space)

    @st.composite
    def lists(draw):
        bases = draw(st.lists(base, min_size=1, max_size=3))
        out = list(bases)
        for _ in range(draw(st.integers(1, max_size - len(bases)))):
            b = draw(st.sampled_from(bases))
            sl, dm = dict(b["slots"]), dict(b["dims"])
            for s in draw(st.lists(st.sampled_from(ALL_SLOTS), max_size=2)):
                sl[s] = draw(st.sampled_from(space.vals[s]))
            if draw(st.booleans()):
                fs = set(filter(None, sl.get("feats", "").split("+")))
                fs ^= {draw(st.sampled_from([f for f in space.feats if f != "rf_*"]))}
                sl["feats"] = "+".join(sorted(fs))
            keys = [k for k, v in dm.items() if isinstance(v, int) and not isinstance(v, bool)]
            for k in draw(st.lists(st.sampled_from(keys), max_size=8)):
                dm[k] = max(0, dm[k] + draw(st.integers(-1, 3)))
            if dm.get("moe_sig") and draw(st.booleans()):
                s = list(dm["moe_sig"])
                for ix in draw(st.lists(st.sampled_from([0, 1, 2, 3, 8, 11, 12, 13]), max_size=3)):
                    s[ix] = max(0, s[ix] + draw(st.integers(-1, 4)))
                if s[0] == 0:
                    s[1] = 0
                elif s[1] == 0:
                    s[1] = 1
                dm["moe_sig"] = tuple(s)
            if draw(st.booleans()):
                dm["rope_cap"] = tuple(x + draw(st.integers(0, 3)) for x in dm.get("rope_cap", ()))
            out.append({"slots": sl, "dims": dm})
        return out
    return lists()


def differential_hypothesis(space, examples=150, modes=CODE_MODES,
                            flags=((False, False), (True, False), (False, True)), log=print):
    """Model vs emul_matrix on Hypothesis-generated point lists (every ordered pair of each list)."""
    from hypothesis import HealthCheck, given, settings
    from hypothesis import strategies as st
    bad, pairs, edges = [], [0], [0]
    for ctx, vocab in flags:
        with _Flags(ctx, vocab):
            model = Model(space, ctx, vocab, ROPE_K_DIFF, 4)
            ev = Evaluator(model)

            @settings(max_examples=examples, deadline=None, derandomize=True, database=None,
                      suppress_health_check=list(HealthCheck))
            @given(point_lists(space), st.sampled_from(modes))
            def check(P, mode):
                real = G.emul_matrix(P, mode=mode)
                mine = ev.matrix(P, mode)
                pairs[0] += real.size
                edges[0] += int(real.sum())
                for i, j in np.argwhere(real != mine):
                    bad.append((ctx, vocab, mode, i == j, P[i], P[j], real[i, j], mine[i, j]))
            check()
    log(f"  hypothesis: {pairs[0]:,} synthetic pairs ({edges[0]:,} edges) over {examples} lists x {len(flags)} "
        f"flag sets, {len(bad)} disagreements")
    for b in bad[:5]:
        log(f"      DISAGREE ctx={b[0]} vocab={b[1]} {b[2]} diag={b[3]}:\n        target {b[4]}\n        host   {b[5]}"
            f"\n        code {b[6]} model {b[7]}")
    return len(bad)


