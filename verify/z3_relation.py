# concrete evaluation: a numpy interpreter of the Z3 AST (the SAME expression the solver sees)

def _nary(f):
    return lambda a: f.reduce(np.broadcast_arrays(*a)) if len(a) > 1 else np.asarray(a[0])


_OPS = {
    z3.Z3_OP_AND: _nary(np.logical_and),
    z3.Z3_OP_OR: _nary(np.logical_or),
    z3.Z3_OP_NOT: lambda a: np.logical_not(a[0]),
    z3.Z3_OP_IMPLIES: lambda a: np.logical_or(np.logical_not(a[0]), a[1]),
    z3.Z3_OP_EQ: lambda a: np.equal(a[0], a[1]),
    z3.Z3_OP_DISTINCT: lambda a: np.not_equal(a[0], a[1]),
    z3.Z3_OP_LE: lambda a: np.less_equal(a[0], a[1]),
    z3.Z3_OP_LT: lambda a: np.less(a[0], a[1]),
    z3.Z3_OP_GE: lambda a: np.greater_equal(a[0], a[1]),
    z3.Z3_OP_GT: lambda a: np.greater(a[0], a[1]),
    z3.Z3_OP_ADD: lambda a: sum(a[1:], a[0]),
    z3.Z3_OP_SUB: lambda a: a[0] - sum(a[1:]) if len(a) > 1 else -a[0],
    z3.Z3_OP_UMINUS: lambda a: -a[0],
    z3.Z3_OP_MUL: lambda a: np.prod(np.broadcast_arrays(*a), axis=0) if len(a) > 1 else a[0],
    z3.Z3_OP_ITE: lambda a: np.where(a[0], a[1], a[2]),
    # SMT div / mod: floor division and a non-negative remainder for a positive divisor (every divisor in the
    # model is guarded positive where the branch is taken; np.where evaluates both branches, so guard zeros)
    z3.Z3_OP_IDIV: lambda a: np.floor_divide(a[0], np.where(np.asarray(a[1]) == 0, 1, a[1])),
    z3.Z3_OP_MOD: lambda a: np.mod(a[0], np.where(np.asarray(a[1]) == 0, 1, a[1])),
}


def np_eval(e, env, memo=None):
    memo = {} if memo is None else memo
    stack = [e]
    while stack:                                   # iterative post-order (deep If chains)
        x = stack[-1]
        i = x.get_id()
        if i in memo:
            stack.pop()
            continue
        if z3.is_true(x):
            memo[i] = True
        elif z3.is_false(x):
            memo[i] = False
        elif z3.is_int_value(x):
            memo[i] = x.as_long()
        elif z3.is_const(x) and x.decl().kind() == z3.Z3_OP_UNINTERPRETED:
            memo[i] = env[x.decl().name()]
        else:
            kids = x.children()
            todo = [k for k in kids if k.get_id() not in memo]
            if todo:
                stack.extend(todo)
                continue
            kind = x.decl().kind()
            if kind not in _OPS:
                raise NotImplementedError(f"op {x.decl()} in the model")
            memo[i] = _OPS[kind]([memo[k.get_id()] for k in kids])
        stack.pop()
    return memo[e.get_id()]


def _blocks(fw, fw_k):
    cnt = Counter(int(w) for w in fw)
    bl = sorted(cnt.items(), key=lambda kv: -kv[0])
    if len(bl) > fw_k:
        raise ValueError(f"{len(bl)} distinct per-layer FFN widths > fw_k={fw_k}")
    return bl + [(0, 0)] * (fw_k - len(bl))


def point_values(model, p):
    """A real / synthetic emul_matrix point -> {var suffix: value} for one shape."""
    S, dm, sl = model.S, p["dims"], p["slots"]
    out = {s: S.code(s, sl[s]) for s in ALL_SLOTS}
    fs = sl.get("feats", "") or ""
    out["uni"] = fs.startswith("*")
    on = set(filter(None, fs.lstrip("*").split("+")))
    unknown = {x for x in on if x not in S.feats}
    for x in unknown:                              # an unknown recurrent family: the sentinel; others are free
        if x.startswith("rf_"):
            raise ValueError(f"recurrent feature {x} not in the universe")
    for f in S.feats:
        out[f"f:{f}"] = f in on
    names = BASE_DIMS + KIND_DIMS + (CTX_DIMS if model.ctx else ()) + (VOCAB_DIMS if model.vocab else ())
    for k in RK_DIMS:                              # (fr-positions: absent = every attention layer rotates)
        kk, which = k[2:].split("_")
        out[k] = int(dm.get(k, G._kind_count(p, kk, which)))
    for k in names:
        if k in KIND_DIMS:
            kk, which = k[1:].split("_")
            out[k] = int(G._kind_count(p, kk, which))
        elif k in FALLBACK:
            out[k] = int(dm.get(k, dm.get(FALLBACK[k], 0)))
        elif k == "alibi_sinv":
            out[k] = alibi_sinv(dm)
        elif k in CTX_CODED and k in dm and dm[k] is None:
            out[k] = G.CTX_UNKNOWN                 # (round 3: an unknown context, as emul_matrix's _ctx_codes reads it)
        elif k == "norm_groups" and isinstance(dm.get(k), str):
            out[k] = 1                             # (release: a branch set plays a target as one group, _r3_masks)
        elif k in NGS_DIMS:
            ng = dm.get("norm_groups")
            gs = [max(int(x), 1) for x in G.branches(ng)] if isinstance(ng, str) else []
            if len(gs) > NGS_K:
                raise ValueError(f"norm_groups branch set {ng!r} longer than NGS_K={NGS_K}")
            i = NGS_DIMS.index(k)
            out[k] = gs[i] if i < len(gs) else 0
        else:
            out[k] = int(dm.get(k, 0))
    sched = tuple(dm.get("rope_sched", ()))
    cap = tuple(dm.get("rope_cap", sched))
    if len(sched) > model.k or len(cap) > model.k:
        raise ValueError(f"rope tuple longer than rope_k={model.k}: {sched} {cap}")
    for i in range(model.k):
        out[f"rope_sched{i}"] = int(sched[i]) if i < len(sched) else 0
        out[f"rope_cap{i}"] = int(cap[i]) if i < len(cap) else 0
    fw = tuple(dm.get("ffn_widths") or ())
    out["fw_listed"] = bool(fw)
    for i, (w, n) in enumerate(_blocks(fw, model.fw_k)):
        out[f"fw_w{i}"], out[f"fw_n{i}"] = w, n
    out["sched_len"] = len(sched)
    kind = dm.get("rope_kind", "") or ""
    out["rope_kind"] = S.kind_idx.get(kind, S.kind_idx["<kind1>"])
    shapes = G._kv_shape_list(p)                   # (round 3, batch 2d: + the V width; the per-shape layer counts)
    if len(shapes) > KV_SHAPES:
        raise ValueError(f"{len(shapes)} attention shapes > KV_SHAPES={KV_SHAPES}")
    cnt = G._kv_counts(p, len(shapes))
    for i in range(KV_SHAPES):
        sh = shapes[min(i, len(shapes) - 1)]
        for c, v in zip(("h", "g", "d", "v"), sh):
            out[f"kvs{i}_{c}"] = int(v)
        out[f"kvs{i}_n"] = int(cnt[i]) if i < len(shapes) else 0
    out["cbad_par"] = bool(p.get("_cbad_par", False))
    out["cbad_ln"] = bool(p.get("_cbad_ln", False))
    out["cbad_aw"] = bool(p.get("_cbad_aw", False))
    # round 3 (kind_order): the sequence code and the host-side bits / counts (ko_values, cached per sequence)
    ks = str(dm.get("kseq", "") or "")
    out["kseq"] = S.kseq_idx[ks]
    out.update(ko_values(S, ks, bool(int(dm.get("win_free", 0)) > 0 and G._p5("window")), bool(model.ctx)))
    rks = str(dm.get("rkseq", ks) or "")           # (release, fr-positions: absent = every attention layer rotates)
    out["rkseq"] = S.kseq_idx[rks]
    out.update({"r" + k: v for k, v in ko_values(S, rks, bool(int(dm.get("win_free", 0)) > 0 and G._p5("window")),
                                                  bool(model.ctx)).items()})
    for k in R3_CAT:                               # round 3: an unknown value is the sentinel (it nests only itself)
        idx = S.r3_idx[k]
        out[k] = idx.get(str(dm.get(k, "") or ""), idx[R3_SENTINEL[k]])
    sig = dm.get("moe_sig")
    out["moe_none"] = not sig
    T = dict(zip(G.MOE_SIG, sig)) if sig else {}
    for k in MOE_INT:
        out[f"moe_{k}"] = int(T.get(k, 0))
    out["moe_renorm"] = S.cat_idx["renorm"][T.get("renorm", "")]
    out["moe_score"] = S.cat_idx["score"][T.get("score", "")]
    out["moe_group_cap"] = S.cat_idx["group_cap"][T.get("group_cap", "")]
    out["moe_latent_norm"] = S.cat_idx["latent_norm"][T.get("latent_norm", "")]       # round 3, batch 3a
    for v in S.renorm_vals:
        out[f"rcap:{v}"] = v in T.get("renorm_cap", ())
    for v in S.score_vals:
        out[f"scap:{v}"] = v in T.get("score_cap", ())
    return out


def _ko_reach(ctx, loose):
    """emul_matrix's kind_match reach for a mode: KIND_REACH, + recurrent / shared targets for attention hosts
    (mixgap), + full targets for sliding hosts (USE_CONTEXT)."""
    reach = ({hk: tk + (("R", "S") if hk in ("FU", "FT", "LU", "LT") else ()) for hk, tk in G.KIND_REACH.items()}
             if loose else dict(G.KIND_REACH))
    if ctx:
        reach["LU"] = reach["LU"] + ("FU", "FT")
        reach["LT"] = reach["LT"] + ("FT",)
    return G._tok_reach(reach)


@functools.lru_cache(maxsize=None)
def _ko_cached(vals, ks, hfull, ctx):
    out = {}
    h = G._kseq_runs(ks)
    for r, loose in (("b", False), ("l", True)):
        R = _ko_reach(ctx, loose)
        for a in range(1, len(vals)):
            ta = G._kseq_runs(vals[a])
            for f in KO_FACTORS:
                for ad in KO_ADDS:
                    for cv in (0, 1):
                        out[f"ko:{a}:{f}:{ad}:{cv}:{r}"] = (bool(h) and
                                                            G.kind_order_ok(ta, h, f, ad, bool(cv), hfull, R))
        hh = G._seq_tf(h, hfull)
        lay = [x for x, c in hh for _ in range(c)]
        for ad in KO_ADDS:
            if not ad:
                continue
            fu = [i for i, x in enumerate(lay) if "FU" in R.get(x, ())]
            for k in G.LAYER_KINDS:
                out[f"koa:{k}:{ad}:{r}"] = (sum(1 for x in lay[fu[ad - 1] + 1:] if k in R.get(x, ()))
                                            if len(fu) >= ad else -1)
    return out


def ko_values(S, ks, hfull, ctx):
    return _ko_cached(tuple(S.kseq_vals), ks, hfull, ctx)


def env_for(model, T, H, P_t, P_h, diag=False):
    """Variables of T as column vectors over P_t, of H as row vectors over P_h (diag: both flat, elementwise)."""
    env = {}
    for sh, pts, shape in ((T, P_t, (-1,) if diag else (-1, 1)), (H, P_h, (-1,) if diag else (1, -1))):
        vals = [point_values(model, p) for p in pts]
        for key in vals[0]:
            arr = np.array([v[key] for v in vals])
            env[f"{sh.name}.{key}"] = (arr.astype(bool) if arr.dtype == bool else arr.astype(np.int64)).reshape(shape)
    return env


class Evaluator:
    """model relation expressions, cached per (mode, same), evaluated over all pairs of point lists."""

    def __init__(self, model):
        self.m = model
        self.T, self.H = model.shape("T"), model.shape("H")
        self._rel = {}

    def expr(self, mode, same=False):
        key = (mode, same)
        if key not in self._rel:
            self._rel[key] = self.m.rel(self.T, self.H, mode, same)
        return self._rel[key]

    def matrix(self, P, mode, P_h=None, chunk=64, diagonal=True):
        """[i, j] = the model's relation for target P[i], host P_h[j] (P_h default P; the diagonal of a square
        matrix uses the code's i == j form when diagonal). A square matrix is evaluated in two passes: the hosts'
        set-context flags (cbad_par / cbad_ln: the code's compensator drop reads the whole point set) are read off
        the first pass, as emul_matrix reads them off its matrix before the drop."""
        square = P_h is None
        P_h = P if P_h is None else P_h
        out = self._matrix(P, mode, P_h, chunk, diagonal and square)
        if square and mode != "capacity":
            P2 = self._context(P, mode, out)
            if P2 is not None:
                out = self._matrix(P2, mode, P2, chunk, diagonal)
        return out

    def _context(self, P, mode, first):
        """The point set's context flags off a first pass `first` (the relation before the set-dependent drops): the
        unmeasured parallel / LayerNorm-beta targets each host plays (cbad_par / cbad_ln), and (round 3, batch 3b)
        whether it plays some target through an act-width fit (cbad_aw: kmul > 1). None if no flag is set."""
        par = np.array([p["slots"].get("block") == "parallel" and not p["dims"].get("rms_ok") for p in P])
        ln = np.array([p["slots"].get("norm") == "LayerNorm" and bool(p["dims"].get("ln_beta"))
                       and not p["dims"].get("rms_ok") for p in P])
        bad_par = (first & par[:, None]).any(0)
        bad_ln = (first & ln[:, None]).any(0)
        bad_aw = np.zeros(len(P), bool)
        if G._r3("spot_act_width_oai"):
            self.expr(mode)                                    # (builds the parts, so kmul_of holds the T, H pair)
            km = self.m.kmul_of[(self.T.name, self.H.name, mode, False)]
            with np.errstate(all="ignore"):
                K = np.broadcast_to(np.asarray(np_eval(km, env_for(self.m, self.T, self.H, P, P)), np.int64),
                                    (len(P), len(P)))
            off = ~np.eye(len(P), dtype=bool)
            bad_aw = (first & (K > 1) & off).any(0)
        if not (bad_par.any() or bad_ln.any() or bad_aw.any()):
            return None
        return [dict(p, _cbad_par=bool(a), _cbad_ln=bool(b), _cbad_aw=bool(c))
                for p, a, b, c in zip(P, bad_par, bad_ln, bad_aw)]

    def _matrix(self, P, mode, P_h, chunk, diagonal):
        out = np.zeros((len(P), len(P_h)), bool)
        e = self.expr(mode)
        with np.errstate(all="ignore"):
            for a in range(0, len(P), chunk):
                env = env_for(self.m, self.T, self.H, P[a:a + chunk], P_h)
                r = np_eval(e, env)
                out[a:a + chunk] = np.broadcast_to(np.asarray(r, bool), (min(chunk, len(P) - a), len(P_h)))
            if diagonal:
                env = env_for(self.m, self.T, self.H, P, P, diag=True)
                d = np.broadcast_to(np.asarray(np_eval(self.expr(mode, True), env), bool), (len(P),))
                out[np.arange(len(P)), np.arange(len(P))] = d
        return out

    def parts_matrix(self, P, mode, P_h=None):
        """{part name: matrix} (off-diagonal semantics). A square matrix reads the hosts' set-context flags (cbad_par /
        cbad_ln) off a first pass, as matrix() does (round 3, batch 1: the unmeasured parallel / LayerNorm-beta targets
        Bitsy, Parler-TTS and Nae1 make the compensator drop fire among the real shapes)."""
        square = P_h is None
        P_h = P if P_h is None else P_h
        if square and mode != "capacity":
            first = self._matrix(P, mode, P, 64, True)
            P2 = self._context(P, mode, first)
            if P2 is not None:
                P = P_h = P2
        parts = self.m.parts(self.T, self.H, mode)
        out = {}
        with np.errstate(all="ignore"):
            env = env_for(self.m, self.T, self.H, P, P_h)
            memo = {}
            for k, e in parts.items():
                out[k] = np.broadcast_to(np.asarray(np_eval(e, env, memo), bool), (len(P), len(P_h))).copy()
        return out

    def wf_vector(self, P):
        X = self.m.shape("X")
        vals = [point_values(self.m, p) for p in P]
        env = {f"X.{k}": np.array([v[k] for v in vals]) for k in vals[0]}
        return np.broadcast_to(np.asarray(np_eval(self.m.wf(X), env), bool), (len(P),)).copy()


def check_kv_closed_form(box=(24, 12, 24, 12)):
    """need_heads == graph.model_graph.kv_hosts_needed on a box (via the interpreter)."""
    kt, gt, gh, q = (z3.Int(n) for n in ("kt", "gt", "gh", "q"))
    e = need_heads(kt, gt, gh, q)
    g = np.meshgrid(*[np.arange(0, b + 1) for b in box], indexing="ij")
    env = dict(zip(("kt", "gt", "gh", "q"), [x.reshape(-1).astype(np.int64) for x in g]))
    env["q"] = np.maximum(env["q"], 1)                       # kv_heads_fit's q is >= 1
    with np.errstate(all="ignore"):
        mine = np.asarray(np_eval(e, env))
    code = np.array([G.kv_hosts_needed(*map(int, a)) for a in zip(env["kt"], env["gt"], env["gh"], env["q"])])
    return int((mine != code).sum()), code.size


