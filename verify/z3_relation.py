def _outcome(r):
    return "PROVED" if r == z3.unsat else ("REFUTED" if r == z3.sat else "UNKNOWN (timeout)")


def _overall(out):
    sts = [v[0] if isinstance(v, tuple) else v["status"] for v in out.values()]
    return "PROVED" if all(x == "PROVED" for x in sts) else ("REFUTED" if "REFUTED" in sts else "UNKNOWN (timeout)")


def prove_reflexive(model, mode, timeout_ms):
    """Per conjunct: wf(A) and not conjunct(A, A) (the code's diagonal) is unsat. Returns (status, details)."""
    a = model.shape("A")
    out = OrderedDict()
    ctx = model.context([a], [a], mode) if mode != "capacity" else []
    for name, e in model.parts(a, a, mode, same=True).items():
        r, m, s = _check([model.wf(a), z3.Not(e)] + ctx, timeout_ms)
        cex = None
        if r == z3.sat:
            rr, mr, sr = _check([model.realistic(a), z3.Not(e)] + ctx, timeout_ms)
            if rr == z3.sat:
                m, s = mr, sr
            m = _simplify(model, s, m, [a])
            pa = shape_value(model, m, a)
            cex = {"A": pa, "code": bool(code_says([pa], mode, model.ctx, model.vocab)[0, 0]),
                   "realistic": rr == z3.sat, "on_realistic": _outcome(rr)}
        out[name] = (_outcome(r), cex)
    return _overall(out), out


def prove_monotone(model, lo, hi, timeout_ms):
    """Per conjunct of the higher mode: wf, rel_lo(A, B), not conjunct_hi(A, B) is unsat. First syntactically: a
    conjunct that is the same expression in both modes (after the proved equality of the sink's spare head dims
    add_hd, substituted) follows from rel_lo. Otherwise a solver query, with the lemma instances that conjunct
    needs: need_antitone_q (and the packing factors' order where the solver proves it) for kv_heads, the widening
    fact x (d + a) // d >= x for the capacities."""
    a, b = model.shape("A"), model.shape("B")
    P_lo = model.parts(a, b, lo)
    ad_lo = model.last_add_hd
    P_hi = model.parts(a, b, hi)
    ad_hi = model.last_add_hd
    r_eq, _, _ = _check([model.wf(a), model.wf(b), ad_lo != ad_hi], timeout_ms)
    same_ad = r_eq == z3.unsat
    kv_lem, q_order = [], True
    for i in range(KV_SHAPES):
        for j in range(KV_SHAPES):
            _, q_lo, kt, gt, gh, _ = model.kv_shape_fit(a, b, lo, i, j, ad_lo)
            q_hi = model.kv_shape_fit(a, b, hi, i, j, ad_hi)[1]
            kv_lem.append(z3.Implies(q_hi >= q_lo, need_heads(kt, gt, gh, q_hi) <= need_heads(kt, gt, gh, q_lo)))
            # floor_antitone: x // (d + a) <= x // d (x, a >= 0, d >= 1) -- the spare head dims only lower q
            x_, d_ = b.kvs[j][2], a.kvs[i][2]
            fl_hint = [z3.Implies(z3.And(x_ >= 0, ad_lo >= 0), x_ / imax(d_ + ad_lo, 1) <= x_ / imax(d_, 1))]
            if _check([model.wf(a), model.wf(b), q_lo > q_hi] + fl_hint, timeout_ms)[0] == z3.unsat:
                kv_lem.append(q_lo <= q_hi)
            else:
                q_order = False
    hs = imax(a.d["head_dim"], 1)
    cap_lem = [z3.Implies(z3.And(x >= 0, ad_lo >= 0), x * (a.d["head_dim"] + ad_lo) / hs >= x)
               for x in (a.d["q_cap"], a.d["kv_cap"])] + ([ad_lo == ad_hi] if same_ad else [])
    lemmas = {"kv_heads": kv_lem + ([ad_lo == ad_hi] if same_ad else []), "q_cap": cap_lem, "kv_cap": cap_lem}

    def flags(mode, tag):
        """The point set {A, B}'s context flags for `mode`, as fresh variables (they differ between modes)."""
        sub = [(x.cbad_par, z3.Bool(f"{x.name}.cbad_par@{tag}")) for x in (a, b)] + \
              [(x.cbad_ln, z3.Bool(f"{x.name}.cbad_ln@{tag}")) for x in (a, b)] + \
              [(x.cbad_aw, z3.Bool(f"{x.name}.cbad_aw@{tag}")) for x in (a, b)]
        cons = model.context([a, b], [a, b], mode) if mode != "capacity" else []
        return sub, [z3.substitute(c, *sub) for c in cons]
    s_lo, c_lo = flags(lo, "lo")
    s_hi, c_hi = flags(hi, "hi")
    base = [model.wf(a), model.wf(b), z3.substitute(z3.And(*P_lo.values()), *s_lo)] + c_lo + c_hi
    out = OrderedDict()
    for name, e in P_hi.items():
        e_cmp = z3.substitute(e, (ad_hi, ad_lo)) if same_ad and not z3.eq(ad_hi, ad_lo) else e
        if name in P_lo and name not in CTX_PARTS and z3.eq(z3.simplify(P_lo[name]), z3.simplify(e_cmp)):
            out[name] = ("PROVED", None)            # the same conjunct in both modes: implied by rel_lo
            continue
        if name == "kv_heads" and q_order and (same_ad or hi == "capacity"):
            # modular: per shape pair (i, j) the two modes differ only in the packing factor q (have, the head
            # counts and groups are mode-free; q_lo <= q_hi proved above), so with N = kv_hosts_needed(.., q) the
            # lemma need_antitone_q gives N_hi <= N_lo; the rest is propositional
            lo_c, hi_c, rel_c, mode_free = [], [], [], True
            for i in range(KV_SHAPES):
                alo, ahi = [], []
                for j in range(KV_SHAPES):
                    have, _, _, _, _, kh = model.kv_shape_fit(a, b, lo, i, j, ad_lo)
                    have2, _, kt2, gt2, gh2, kh2 = model.kv_shape_fit(a, b, hi, i, j, ad_hi)
                    nlo, nhi = z3.Int(f"N.lo{i}{j}"), z3.Int(f"N.hi{i}{j}")
                    alo.append(z3.Or(z3.Not(have), kh >= nlo))
                    ahi.append(z3.Or(z3.Not(have2), kh2 >= nhi))
                    mode_free &= z3.eq(z3.simplify(have), z3.simplify(have2)) and z3.eq(z3.simplify(kh), z3.simplify(kh2))
                    rel_c += [nhi <= nlo, have == have2, kh == kh2]
                lo_c.append(z3.Or(*alo))
                hi_c.append(z3.Or(*ahi))
            if mode_free and _check(rel_c + [z3.And(*lo_c), z3.Not(z3.And(*hi_c))], timeout_ms)[0] == z3.unsat:
                out[name] = ("PROVED", None)
                continue
        if name == "kv_heads" and same_ad:
            X = z3.Int("X.add_hd")                   # the same function of the spare head dims, which agree
            if z3.eq(z3.simplify(model.kv_fit(a, b, lo, X)), z3.simplify(model.kv_fit(a, b, hi, X))):
                out[name] = ("PROVED", None)
                continue
        r, m, s = _check(base + lemmas.get(name, []) + [z3.Not(z3.substitute(e, *s_hi))], timeout_ms)
        cex = None
        if r == z3.sat:
            m = _simplify(model, s, m, [a, b])
            pa, pb = shape_value(model, m, a), shape_value(model, m, b)
            R_lo = code_says([pa, pb], lo, model.ctx, model.vocab)
            R_hi = code_says([pa, pb], hi, model.ctx, model.vocab)
            cex = {"target": pa, "host": pb, "confirmed_on_code": bool(R_lo[0, 1] and not R_hi[0, 1])}
        out[name] = (_outcome(r), cex)
    return _overall(out), out


def prove_alias(model, timeout_ms, a_mode="nomix", b_mode="payable"):
    """a_mode and b_mode are the same relation on every well-formed pair and on the diagonal."""
    a, b = model.shape("A"), model.shape("B")
    ctx = model.context([a, b], [a, b], b_mode)          # (the same flags: payable = nomix line by line)
    r1, _, _ = _check([model.wf(a), model.wf(b), model.rel(a, b, a_mode) != model.rel(a, b, b_mode)] + ctx, timeout_ms)
    r2, _, _ = _check([model.wf(a), model.rel(a, a, a_mode, True) != model.rel(a, a, b_mode, True)]
                      + model.context([a], [a], b_mode), timeout_ms)
    if (r1, r2) == (z3.unsat, z3.unsat):
        return "PROVED"
    return "REFUTED" if z3.sat in (r1, r2) else "UNKNOWN (timeout)"


# conjuncts whose transitivity query is split into cases (one solver call per assignment, as assumptions)
SPLITS = {"rec": lambda a, b, c: [(x.d["rc_rule"], range(6)) for x in (a, b, c)]}


def _check_split(cons, timeout_ms, split):
    """unsat if every case is unsat; sat (with a model) if one is; else unknown."""
    s = z3.Solver()
    s.set("timeout", int(timeout_ms))
    s.add(*cons)
    unknown = False
    for vals in itertools.product(*[list(d) for _, d in split]):
        r = s.check(*[v == x for (v, _), x in zip(split, vals)])
        if r == z3.sat:
            s.add(*[v == x for (v, _), x in zip(split, vals)])
            s.check()
            return z3.sat, s.model(), s
        unknown |= r == z3.unknown
    return (z3.unknown if unknown else z3.unsat), None, s


def transitivity(model, mode, timeout_ms, parts=None, log=None, min_budget_s=300):
    """Transitivity, conjunct by conjunct: for each conjunct c of rel(A, C), is "rel(A, B), rel(B, C), not c(A, C)"
    unsat over well-formed A, B, C? First with c alone on both hops (c is a preorder by itself), then with the
    whole relation on both hops (for the recurrent rules split by the three rc_rules). Every query carries the
    instances of the integer lemmas (div_hints, rec_hints). If not unsat, a counterexample is searched among
    REALISTIC shapes first (wf + the clauses observed on the zoo), simplified (_simplify) and confirmed on the real
    emul_matrix; its cause is c. If no realistic counterexample exists, c is transitive on realistic shapes and the
    wf counterexample shows which construction-level freedom breaks it. Returns (overall status, {conjunct: dict})."""
    a, b, c = model.shape("A"), model.shape("B"), model.shape("C")
    PAB, PBC, PAC = (model.parts(x, y, mode) for x, y in ((a, b), (b, c), (a, c)))
    # the point set is {A, B, C}: the context flags of the targets A, B (the compensator drop)
    ctx = model.context([a, b], [a, b, c], mode, {("A", "B"): PAB, ("B", "C"): PBC, ("A", "C"): PAC}) \
        if mode != "capacity" else []
    # (the context constraints repeat the relation over the set's pairs: added only for the conjunct that reads them,
    # the compensator; elsewhere the flags are left free -- weaker hypotheses, so an unsat answer is still a proof,
    # and every counterexample is confirmed on the code)
    hints = div_hints(a, b, c) + rec_hints(a, b, c)
    wf0 = [model.wf(x) for x in (a, b, c)] + hints
    real0 = [model.realistic(x) for x in (a, b, c)] + hints
    rAB, rBC = z3.And(*PAB.values()), z3.And(*PBC.values())
    out = OrderedDict()

    ev = Evaluator(model)

    def cex(m, s, realistic):
        m = _simplify(model, s, m, [a, b, c], budget_s=min_budget_s)
        pts = [shape_value(model, m, x) for x in (a, b, c)]
        R = code_says(pts, mode, model.ctx, model.vocab)
        conf = bool(R[0, 1] and R[1, 2] and not R[0, 2])
        if conf:                                      # then 1-minimal on the code itself, in its wf class
            pts = ddmin_code(model.S, pts, mode, wf_pred(model, realistic), model.ctx, model.vocab)
        pm = ev.parts_matrix(pts, mode) if conf else None
        fails = ([k for k, v in pm.items() if not v[0, 2]] if conf else
                 [k for k, e in PAC.items() if not z3.is_true(m.eval(e, model_completion=True))])
        return {"A": pts[0], "B": pts[1], "C": pts[2], "realistic": realistic, "confirmed_on_code": conf,
                "fails": fails}

    hyps = [(f"AB.{k}", e) for k, e in PAB.items()] + [(f"BC.{k}", e) for k, e in PBC.items()] + \
        ([("context", z3.And(*ctx))] if ctx else [])

    def lazy(base, name):
        """Lazy hypotheses (CEGAR): start from the conjunct on both hops, add the hop conjuncts a candidate model
        violates, repeat. unsat with a subset of the hypotheses is a proof (fewer hypotheses, a weaker claim
        refuted); a model violating none is a counterexample of the whole relation."""
        active = [PAB[name], PBC[name]]
        used = {f"AB.{name}", f"BC.{name}"}
        while True:
            cons = base + active + [z3.Not(PAC[name])]
            r, m, s = _check(cons, timeout_ms, seeds=(0, 7))
            if r == z3.unknown and name in SPLITS:
                r, m, s = _check_split(cons, timeout_ms, SPLITS[name](a, b, c))
            if r != z3.sat:
                return r, None, None, f" ({len(used)} hop conjuncts)"
            bad = [(k, e) for k, e in hyps if k not in used and not z3.is_true(m.eval(e, model_completion=True))]
            if not bad:
                # every hypothesis holds at m: assert them all, so _simplify keeps a counterexample of the WHOLE relation
                s.add(*[e for k, e in hyps if k not in used])
                return r, m, s, ""
            for k, e in bad:
                used.add(k)
                active.append(e)

    def full(base, name):
        return lazy(base, name)
    for name in PAC:
        if parts and name not in parts:
            continue
        wf, real = (wf0 + ctx, real0 + ctx) if name in CTX_PARTS else (wf0, real0)
        t0 = time.time()
        r1, _, _ = _check(wf + [PAB[name], PBC[name], z3.Not(PAC[name])], timeout_ms)
        if r1 == z3.unsat:
            out[name] = {"status": "PROVED", "how": "the conjunct alone is transitive"}
        else:
            r2, m2, s2, sp2 = full(wf, name)
            if r2 == z3.unsat:
                out[name] = {"status": "PROVED", "how": "with the relation on both hops" + sp2}
            else:
                r3, m3, s3, sp3 = full(real, name)
                if r3 == z3.sat:
                    out[name] = {"status": "REFUTED", "how": "realistic counterexample", "cex": cex(m3, s3, True)}
                elif r2 == z3.sat:
                    out[name] = {"status": "REFUTED", "cex": cex(m2, s2, False),
                                 "how": "wf counterexample; " + ("PROVED on realistic shapes" + sp3 if r3 == z3.unsat
                                                                 else "realistic: unknown (timeout)")}
                elif r3 == z3.unsat:
                    out[name] = {"status": "UNKNOWN (timeout)", "how": "PROVED on realistic shapes" + sp3
                                                                       + "; wf: unknown (timeout)"}
                else:
                    out[name] = {"status": "UNKNOWN (timeout)",
                                 "how": f"conjunct alone: {_outcome(r1)}; whole relation, wf and realistic: timeout"}
        out[name]["s"] = round(time.time() - t0, 1)
        if log:
            log(f"     {mode:8s} {name:14s} {out[name]['status']} ({out[name]['how']}; {out[name]['s']}s)")
    return _overall(out), out


def join_constraints(model, t, J, M):
    """The joined host (graph.minimal_emulator.host_point(join(zoo))) for a zoo containing t: its branch slots,
    the universal feature set, gen set per target, every JOIN_AXES dim >= t's (MLA at 2x cache), a uniform stack
    of L >= t's depth with every layer own-KV full attention + a KV register + a recurrent block, MHA KV heads,
    no MoE signature, no ALiBi / rope tables, the free recurrent block."""
    from graph.minimal_emulator import JOIN_AXES
    jh = join_host(M)
    S = model.S
    cons = []
    for s in ALL_SLOTS:
        if s != "gen":
            cons.append(J.c[s] == S.code(s, jh["slots"][s]))
    cons.append(J.c["gen"] == t.c["gen"])
    hf = set(filter(None, jh["slots"]["feats"].lstrip("*").split("+")))
    cons.append(J.uni)
    cons += [J.f[f] == (f in hf) for f in S.feats]
    jd, td = J.d, t.d
    L = jd["eff_layers"]
    cons += [jd["param_layers"] == L, L >= td["eff_layers"], L >= td["param_layers"]]
    for k in JOIN_AXES:
        if k in ("eff_layers", "param_layers") or k not in jd:
            continue
        if k == "kv_cap":
            cons.append(jd[k] >= z3.If(model.mla(t), G.MLA_PENALTY * td[k], td[k]))
        else:
            cons.append(jd[k] >= td[k])
    for k in ("attn_eff", "attn_param", "full_eff", "full_param"):
        cons.append(jd[k] == L)
    for kd in KIND_DIMS:
        cons.append(jd[kd] == (L if kd[1:].split("_")[0] in ("FU", "S", "R") else 0))
    for kd in RK_DIMS:                                 # (fr-positions: the joined host rotates every attention layer)
        cons.append(jd[kd] == jd[kd[1:]])
    cons += [jd["kv_cap_u"] == jd["kv_cap"], jd["q_cap_u"] == jd["q_cap"], jd["qheads_u"] == jd["qheads"],
             jd["head_dim_u"] == jd["head_dim"], jd["mla_qswitch"] == 1, jd["mla_lat_free"] == 1,
             jd["kv_heads"] == jd["qheads"], jd["q_per_kv"] == 1, jd["rc_free"] == 1, jd["rc_rule"] == 0]
    for k in ("rope_pairs_free", "moe_unit_top1", "alibi_heads", "alibi_max", "alibi_bf16", "alibi_off", "alibi_sinv",
              "zamba_mem", "zamba_rank", "zamba_attn_adapt") + P5_INT:
        if k == "eps_lever":
            # round 3, batch 1: the host's norms switch off by weights (host_point eps_lever = 1); read here because
            # the post_norm_attn lever (pna_lever) needs it to host an attention-only post-norm target
            cons.append(jd[k] == int(jh["dims"].get("eps_lever", 0)))
            continue
        cons.append(jd[k] == 0)
    cons += [J.sched_len == 0, J.kind == S.kind_idx[""]]
    cons += [J.kseq == S.kseq_idx[str(jh["dims"].get("kseq", "") or "")]]     # (round 3, kind_order)
    cons += [J.rkseq == J.kseq]                        # (release, fr-positions: the joined host rotates every layer)
    cons += [J.rko[k] == J.ko[k] for k in J.ko] + [J.rko_after[k] == J.ko_after[k] for k in J.ko_after]
    # round 3, batch 1: the host's embedding-norm branch set and fold (host_point), no groups / gated norm / factorization
    cons += [J.r3["emb_norm"] == S.r3_idx["emb_norm"][str(jh["dims"].get("emb_norm", ""))],
             J.r3["gnorm_sites"] == S.r3_idx["gnorm_sites"][""],
             jd["emb_fold"] == int(jh["dims"].get("emb_fold", 0)), jd["emb_rank"] == 0, jd["gnorm_rank"] == 0]
    # (release: the group counts of the zoo as a branch set, join's norm_groups_set -- for a zoo containing t, {1, t's
    # count}; the zoo's other counts are further alternatives, which only add hosting)
    gt = z3.If(td["norm_groups"] > 0, td["norm_groups"], 1)
    cons += [jd["norm_groups"] == 1, jd[NGS_DIMS[0]] == 1, jd[NGS_DIMS[1]] == gt] + [jd[k] == 0 for k in NGS_DIMS[2:]]
    # (round 3, batch 2d: one shape, V as wide as its heads, on all its own-KV attention layers; no grouped o_proj, no
    # query-latent norm, no Canon / MoA branch)
    cons += [z3.And(sh[0] == jd["qheads"], sh[1] == 1, sh[2] == jd["head_dim"], sh[3] == jd["head_dim"],
                    sh[4] == (sum(jd[f"k{k}_eff"] for k in ("FU", "FT", "LU", "LT")) if i == 0 else 0))
             for i, sh in enumerate(J.kvs)]
    cons += [jd["head_dim"] >= sh[3] for sh in t.kvs]               # (the join's heads hold every V width)
    cons += [jd[k] == 0 for k in ("o_groups", "o_rank", "q_lat_norm", "moa_e", "moa_k")]
    # (round 3, batch 3b: the UFFN up bias is a branch, host_point bias_up = 1; no HadamardMLP)
    cons += [jd["bias_up"] == int(jh["dims"].get("bias_up", 0)), jd["hada_n"] == 0]
    cons += [J.r3["canon"] == S.r3_idx["canon"][""]]
    # (round 3, batch 4b: the host's AttnRes / UEngram / value-embedding branches, host_point; no norm-shift biases)
    cons += [J.r3[k] == S.r3_idx[k][str(jh["dims"].get(k, "") or "")] for k in R3_SIGS] + [jd["bias_shift"] == 0]
    # (round 3, nonlm_heads: the readout's biased head of any width, host_point readout_bias = 1; widths via JOIN_AXES)
    cons += [jd["readout_bias"] == int(jh["dims"].get("readout_bias", 0))]
    # (round 3, nope_rope_limit: the join's linear-scaling lever, host_point rope_lin)
    cons += [jd["rope_lin"] == int(jh["dims"].get("rope_lin", 0))]
    cons += [v == 0 for v in J.sched + J.cap]
    cons += [J.moe_none, z3.Not(J.fw_listed)]
    return cons


def join_dominance(model, mode, M, timeout_ms, enum_timeout_ms=None):
    """Per conjunct: is there a REALISTIC target (wf + the clauses observed on the zoo: the join is built from such
    shapes) the joined host does not host? For a categorical conjunct the
    blocked target values are enumerated (slot values / single features); otherwise one minimal counterexample."""
    t, J = model.shape("T"), model.shape("J")
    S = model.S
    base = [model.realistic(t)] + join_constraints(model, t, J, M) + \
        (model.context([t], [t], mode) if mode != "capacity" else [])     # (J is never an unmeasured target)
    P = model.parts(t, J, mode)
    out = OrderedDict()
    et = enum_timeout_ms or timeout_ms
    for name, e in P.items():
        r, m, s = _check(base + [z3.Not(e)], timeout_ms)
        if r != z3.sat:
            out[name] = (_outcome(r), None)
            continue
        slot = name if name in ALL_SLOTS else ("mixer" if name == "mixer_cla" else None)
        if slot:
            blocked = [v for v in S.concrete[slot]
                       if _check(base + [z3.Not(e), t.c[slot] == S.code(slot, v)], et)[0] == z3.sat]
            out[name] = ("REFUTED", {"blocked_values": blocked})
        elif name == "feats":
            blocked = [f for f in S.feats if f != "rf_*" and _check(
                base + [z3.Not(e), t.f[f]] + [z3.Not(t.f[g]) for g in S.feats if g != f], et)[0] == z3.sat]
            out[name] = ("REFUTED", {"blocked_features": blocked})
        else:
            m = _simplify(model, s, m, [t])
            out[name] = ("REFUTED", {"target": shape_value(model, m, t)})
    return _overall(out), out


def real_transitivity(space, P, modes=MODES, log=print):
    """Transitivity violations among the real shapes: pairs (A, C) with some B, A->B->C and not A->C, and the
    conjuncts that fail at (A, C)."""
    model = Model(space, False, False, ROPE_K_DIFF, FW_K_DIFF)
    ev = Evaluator(model)
    out = {}
    for mode in modes:
        ok = G.emul_matrix(P, mode=mode)
        Si = ok.astype(np.int32)
        bad = ((Si @ Si) > 0) & ~ok
        n = int(bad.sum())
        causes = Counter()
        if n:
            idx = np.argwhere(bad)
            rows, cols = sorted(set(idx[:, 0])), sorted(set(idx[:, 1]))
            parts = ev.parts_matrix([P[i] for i in rows], mode, [P[j] for j in cols])
            ri, ci = {i: k for k, i in enumerate(rows)}, {j: k for k, j in enumerate(cols)}
            for i, j in idx:
                for name, mat in parts.items():
                    if not mat[ri[i], ci[j]]:
                        causes[name] += 1
        out[mode] = (n, dict(causes))
        log(f"  real {mode:8s}: {n:,} violating pairs (A, C)" + (f"; failing conjuncts at (A, C): {dict(causes)}"
                                                                  if n else ""))
    return out


def real_monotone(P, log=print):
    """exact <= payable <= mixgap <= capacity on every ordered pair of the real shapes (the real code)."""
    R = {m: G.emul_matrix(P, mode=m) for m in MODES}
    out = {}
    for lo, hi in zip(MODES, MODES[1:]):
        out[(lo, hi)] = int((R[lo] & ~R[hi]).sum())
        log(f"  real {lo} <= {hi}: {out[(lo, hi)]} pairs in {lo} and not in {hi}")
    return out


