    def ctx_trigger(self, x):
        """(parallel unmeasured, LayerNorm-beta unmeasured): a target x that, hosted by y, sets y's cbad flags."""
        unm = z3.Not(x.d["rms_ok"] > 0)
        return (z3.And(self.is_(x, "block", "parallel"), unm),
                z3.And(self.is_(x, "norm", "LayerNorm"), x.d["ln_beta"] > 0, unm))

    def context(self, targets, members, mode, cache=None):
        """The cbad flags of each shape y in `targets` for the point set `members` (the set is exactly these
        shapes): y.cbad_par iff some x in the set is an unmeasured parallel target that y hosts before the drop
        (likewise LayerNorm-beta). cache: {(x name, y name): parts} already built (reused)."""
        cache = {} if cache is None else cache
        out = []
        for y in targets:
            par, ln, aw = [], [], []
            for x in members:
                key = (x.name, y.name)
                if key not in cache:
                    cache[key] = self.parts(x, y, mode, same=x is y)
                pre = [e for k, e in cache[key].items() if k not in CTX_PARTS]
                p_x, l_x = self.ctx_trigger(x)
                pre_ok = z3.And(*pre)
                par.append(z3.And(p_x, pre_ok))
                ln.append(z3.And(l_x, pre_ok))
                # (round 3, batch 3b: y plays x through an act-width fit, before the drops)
                aw.append(z3.And(self.kmul_of[(x.name, y.name, mode, x is y)] > 1, pre_ok))
            out += [y.cbad_par == z3.Or(*par), y.cbad_ln == z3.Or(*ln)]
            if G._r3("spot_act_width_oai"):
                out.append(y.cbad_aw == z3.Or(*aw))
        return out

    def rel(self, t, h, mode, same=False):
        return z3.And(*self.parts(t, h, mode, same).values())

