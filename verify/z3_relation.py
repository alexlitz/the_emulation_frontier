def _check(cons, timeout_ms, seeds=(0,)):
    """One solver call per random seed until one answers (a sat / unsat answer does not depend on the seed)."""
    for seed in seeds:
        s = z3.Solver()
        s.set("timeout", int(timeout_ms))
        s.set("random_seed", seed)
        s.add(*cons)
        r = s.check()
        if r != z3.unknown:
            break
    return r, (s.model() if r == z3.sat else None), s


def _simplify(model, s, m, shapes, budget_s=240, step_ms=10000):
    """Delta-debugging on a satisfiable query: move each variable to its default -- a slot to the zoo's most
    common value, a feature off, an integer to 0 (else 1), whole groups first -- while the query stays sat, then
    halve the remaining integers. The result is LOCALLY minimal (no single variable moves to its default and no
    integer halves within step_ms), not a proved global optimum."""
    S = model.S
    t_end = time.time() + budget_s
    s.set("timeout", int(step_ms))
    cur = [m]

    def val(v):
        return cur[0].eval(v, model_completion=True)

    def attempt(c):
        if time.time() > t_end:
            return False
        s.push()
        s.add(c)
        r = s.check()
        if r == z3.sat:
            mm = s.model()
            s.pop()
            s.add(c)
            cur[0] = mm
            return True
        s.pop()
        return False
    for x in shapes:
        attempt(z3.And(*[z3.Not(v) for v in x.f.values()]))
        attempt(z3.And(*[x.d[k] == 0 for k in G.RC_DIMS + ("rc_rule", "zamba_mem", "zamba_rank", "zamba_attn_adapt")]))
        attempt(z3.And(*[x.d[k] == 0 for k in ("alibi_heads", "alibi_max", "alibi_bf16", "alibi_off", "alibi_sinv")]))
        attempt(z3.And(x.m["E"] == 0, *[x.m[k] == 0 for k in MOE_INT if k not in ("n_dense", "dense_w")]))
        attempt(z3.Not(x.fw_listed))
        attempt(z3.And(*[v == 0 for v in x.sched[1:] + x.cap[1:]]))
    def slots_and_features():
        for x in shapes:
            for sl in ALL_SLOTS:
                b = S.code(sl, S.baseline[sl])
                if val(x.c[sl]).as_long() != b:
                    attempt(x.c[sl] == b)
            for f, v in x.f.items():
                if z3.is_true(val(v)):
                    attempt(z3.Not(v))
    slots_and_features()
    ints = [v for x in shapes for v in x.ints()]
    for v in ints:
        n = val(v).as_long()
        if n != 0 and not attempt(v == 0) and n not in (1, -1):
            attempt(v == (1 if n > 0 else -1))
    slots_and_features()                       # (smaller numbers: the checks are faster the second time)
    for v in ints:
        while time.time() < t_end:
            n = val(v).as_long()
            if abs(n) <= 1 or not attempt(z3.And(v * (1 if n > 0 else -1) <= abs(n) // 2,
                                                 v * (1 if n > 0 else -1) >= 0)):
                break
    return cur[0]


LEMMAS = {
    "dvd_trans": "x | y, y | z, y != 0 => x | z; and z // x = (z // y)(y // x), y = (y // x) x when they divide "
                 "(integer arithmetic; Z3's nonlinear solver does not find these instances by itself)",
    "dvd_scale": "x | y => k x | k y",
    "floor_antitone": "x // (d + a) <= x // d for x, a >= 0, d >= 1",
    "ceil_submult": "ceil(x / z) <= ceil(x / y) ceil(y / z) for x, y, z >= 1",
    "mul_mono": "a <= b, c >= 0 => a c <= b c",
    "need_antitone_q": "kv_hosts_needed(kt, gt, gh, q) is non-increasing in q: the greedy's reach from a start, "
                       "min(y + gh, (y // gt + q) gt), is non-decreasing in q and in y, so by induction every head "
                       "of the larger q ends at least as far (checked exhaustively on a box: check_lemmas)",
}


def div_hints(a, b, c):
    """Instances of the lemma dvd_trans on the shapes (A, B, C) of a transitivity query, for every divisibility the
    relation checks (MLA latents, Zamba blocks, MoE top-k, GDN value heads)."""
    out = []
    for get in (lambda s: s.d["kv_latent"], lambda s: s.d["q_latent"], lambda s: s.d["zamba_mem"],
                lambda s: s.m["k"], lambda s: s.d["rc_v"]):
        x, y, z = get(a), get(b), get(c)
        out.append(z3.Implies(z3.And(dvd(x, y), dvd(y, z), y != 0), dvd(x, z)))
        out.append(z3.Implies(z3.And(dvd(x, y), dvd(y, z), x > 0, y > 0), quo(z, x) == quo(z, y) * quo(y, x)))
        for (p, q_) in ((x, y), (y, z), (x, z)):
            out.append(z3.Implies(z3.And(dvd(p, q_), p > 0), q_ == quo(q_, p) * p))
    return out


def rec_hints(a, b, c):
    """Instances of true integer facts the recurrent rules' transitivity needs (lemmas dvd_trans, dvd_scale,
    ceil_submult, mul_mono) on (A, B, C), built from the same terms as Model.rc_pair_ok: the Mamba-2 group widths
    w = h v // kh (multiples compose, m_AC = m_AB m_BC, the value-head divisibility scales and composes) and the GDN
    key-head replication kt ceil(g_t / g_h) (ceil(x / z) <= ceil(x / y) ceil(y / z))."""
    out = []
    wt = lambda s: quo(s.d["rc_h"] * s.d["rc_v"], s.d["rc_kh"])
    x, y, z = wt(a), wt(b), wt(c)
    out.append(z3.Implies(z3.And(dvd(x, y), dvd(y, z), y != 0), dvd(x, z)))
    out.append(z3.Implies(z3.And(dvd(x, y), dvd(y, z), x > 0, y > 0), quo(z, x) == quo(z, y) * quo(y, x)))
    mAB, mBC = quo(y, x), quo(z, y)
    vA, vB, vC = a.d["rc_v"], b.d["rc_v"], c.d["rc_v"]
    out.append(z3.Implies(z3.And(dvd(vB, mAB * vA), mBC >= 1), dvd(mBC * vB, mBC * (mAB * vA))))
    out.append(z3.Implies(z3.And(dvd(vC, mBC * vB), dvd(mBC * vB, mBC * (mAB * vA)), mBC * vB != 0),
                          dvd(vC, mBC * (mAB * vA))))
    kt = lambda s: imax(s.d["rc_kh"], 1)
    g = lambda s: imax(s.d["rc_h"] / kt(s), 1)
    gA, gB, gC = g(a), g(b), g(c)
    X = cdiv(gA, gB) * cdiv(gB, gC)
    out.append(cdiv(gA, gC) <= X)
    out.append(z3.Implies(kt(a) * cdiv(gA, gB) <= kt(b), kt(a) * cdiv(gA, gB) * cdiv(gB, gC) <= kt(b) * cdiv(gB, gC)))
    out.append(kt(a) * cdiv(gA, gC) <= kt(a) * X)
    return out


def check_lemmas(box=(12, 8, 12, 8)):
    """need_antitone_q on a box, against the code's kv_hosts_needed. Returns the number of violations."""
    import itertools as it
    bad = 0
    for kt, gt, gh in it.product(range(box[0] + 1), range(box[1] + 1), range(box[2] + 1)):
        vals = [G.kv_hosts_needed(kt, gt, gh, q) for q in range(1, box[3] + 1)]
        bad += sum(1 for u, v in zip(vals, vals[1:]) if v > u)
    return bad


def shape_value(model, m, x):
    """A solver model's shape -> an emul_matrix point (the code can evaluate it)."""
    S = model.S
    ev = lambda v: m.eval(v, model_completion=True)
    iv = lambda v: ev(v).as_long()
    slots = {}
    for s in ALL_SLOTS:
        c = iv(x.c[s])
        slots[s] = S.vals[s][c] if 0 <= c < len(S.vals[s]) else f"<code {c}>"
    on = [f for f in S.feats if z3.is_true(ev(x.f[f]))]
    slots["feats"] = ("*" if z3.is_true(ev(x.uni)) else "") + "+".join(on)
    dims = {k: iv(v) for k, v in x.d.items()}
    gs = [dims.pop(k) for k in NGS_DIMS]                                 # (release: a group-count branch set)
    if gs[0] > 0:                                                        # (the model's switch: ngs0 > 0)
        dims["norm_groups"] = "|".join(str(g) for g in gs if g > 0)
    n = max(0, min(iv(x.sched_len), model.k))
    sched, cap = [iv(v) for v in x.sched], [iv(v) for v in x.cap]
    n = max(n, max([i + 1 for i in range(model.k) if sched[i] or cap[i]], default=0))
    dims["rope_sched"] = tuple(sched[:n])
    dims["rope_cap"] = tuple(cap[:n])
    kc = iv(x.kind)
    dims["rope_kind"] = S.kind_vals[kc] if 0 <= kc < len(S.kind_vals) else "<kind?>"
    dims["kv_shapes"] = tuple(tuple(iv(v) for v in sh[:4]) for sh in x.kvs)
    dims["kv_shape_n"] = tuple(iv(sh[4]) for sh in x.kvs)              # (round 3, batch 2d)
    for k in R3_CAT:
        c = iv(x.r3[k])
        dims[k] = S.r3_vals[k][c] if 0 <= c < len(S.r3_vals[k]) else f"<code {c}>"
    c = iv(x.kseq)                                                       # (round 3, kind_order)
    dims["kseq"] = S.kseq_vals[c] if 0 <= c < len(S.kseq_vals) else f"<code {c}>"
    c = iv(x.rkseq)                                                      # (release, fr-positions)
    dims["rkseq"] = S.kseq_vals[c] if 0 <= c < len(S.kseq_vals) else f"<code {c}>"
    if z3.is_true(ev(x.fw_listed)):
        fw = []
        for w, n in zip(x.fw_w, x.fw_n):
            fw += [iv(w)] * max(iv(n), 0)
        dims["ffn_widths"] = tuple(sorted(fw, reverse=True))
    else:
        dims["ffn_widths"] = ()
    if not z3.is_true(ev(x.moe_none)):
        T = {k: iv(x.m[k]) for k in MOE_INT}
        rv = lambda f, vals: vals[iv(x.mc[f])] if 0 <= iv(x.mc[f]) < len(vals) else "<?>"
        T["renorm"], T["score"], T["group_cap"] = (rv("renorm", S.renorm_vals), rv("score", S.score_vals),
                                                  rv("group_cap", S.gcap_vals))
        T["latent_norm"] = rv("latent_norm", S.lnorm_vals)                           # round 3, batch 3a
        T["renorm_cap"] = tuple(v for v in S.renorm_vals if z3.is_true(ev(x.rcap[v])))
        T["score_cap"] = tuple(v for v in S.score_vals if z3.is_true(ev(x.scap[v])))
        dims["moe_sig"] = tuple(T[k] for k in G.MOE_SIG)
    return {"slots": slots, "dims": dims, "members": [f"<{x.name}>"]}


