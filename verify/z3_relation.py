def fmt_min(space, p):
    """A counterexample point as its difference from the default point (_default_point): slots, features, dims."""
    D = _default_point(space)
    sl = [f"{k}={v}" for k, v in p["slots"].items() if k != "feats" and D["slots"].get(k) != v]
    if p["slots"].get("feats"):
        sl.append(f"feats={p['slots']['feats']}")
    dm = []
    for k, v in p["dims"].items():
        if k == "moe_sig":
            if v and v[0]:
                dm.append("moe_sig=" + ",".join(f"{n}={x}" for n, x in zip(G.MOE_SIG, v) if x not in (0, "", ())))
            continue
        if k in ("kv_shapes",) or D["dims"].get(k, 0) == v or v in ((), "", None):
            continue
        dm.append(f"{SHORT.get(k, k)}={v}")
    return "[" + " ".join(sl) + " | " + " ".join(dm) + "]"


