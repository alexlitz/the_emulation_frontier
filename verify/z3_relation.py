def _trans_worker(mode, timeout_ms):
    M, P = real_points()
    space = Space(P, extra=[join_host(M)])
    return transitivity(Model(space), mode, timeout_ms)


def run(modes=MODES, timeout_ms=60000, hyp_examples=150, skip_hypothesis=False, skip_real=False, edges=None,
        log=print, box_n=5, skip_proofs=False):
    from verify import edge_table as E
    t0 = time.time()
    M, P = real_points()
    J = join_host(M)
    space = Space(P, extra=[J])
    R = {"disagreements": 0, "n_points": len(P)}
    log(f"{len(P)} real shapes ({len(M)} models), {len(P) ** 2:,} ordered pairs; slot values: "
        + ", ".join(f"{s} {len(space.vals[s])}" for s in ALL_SLOTS) + f"; {len(space.feats)} features")
    log("\n== well-formedness and the closed forms")
    R["wf_failures"] = check_wf_real(space, P, log)
    R["kv_closed_form"] = check_kv_closed_form()
    R["lemma_violations"] = check_lemmas()
    log(f"  need_heads vs kv_hosts_needed: {R['kv_closed_form'][0]} / {R['kv_closed_form'][1]:,} differ; "
        f"need_antitone_q violations on its box: {R['lemma_violations']}")
    log("\n== differential: Z3 model vs graph.model_graph.emul_matrix")
    if not skip_real:
        R["disagreements"] += differential_real(space, P, log=log, J=J)
    if not skip_hypothesis:
        hp = []
        R["disagreements"] += differential_hypothesis(space, hyp_examples, log=lambda s: (hp.append(s), log(s)))
        m_ = re.search(r"hypothesis: ([\d,]+) synthetic pairs", hp[0]) if hp else None
        R["hyp_pairs"] = int(m_.group(1).replace(",", "")) if m_ else 0
    if not skip_proofs:
        model = Model(space)
        log("\n== reflexivity (per conjunct)")
        for mode in modes:
            R[("refl", mode)] = prove_reflexive(model, mode, timeout_ms)
            log(f"  {mode:8s}: {R[('refl', mode)][0]}")
        log("\n== mode monotonicity (per conjunct of the higher mode)")
        for lo, hi in zip(MODES, MODES[1:]):
            R[("mono", lo, hi)] = prove_monotone(model, lo, hi, timeout_ms)
            log(f"  {lo} <= {hi}: {R[('mono', lo, hi)][0]}")
        R["alias"] = prove_alias(model, timeout_ms)
        log(f"  nomix = payable: {R['alias']}")
        log("\n== transitivity (per conjunct; one process per mode)")
        from concurrent.futures import ProcessPoolExecutor
        with ProcessPoolExecutor(max_workers=len(modes)) as ex:
            futs = {mode: ex.submit(_trans_worker, mode, timeout_ms) for mode in modes}
            for mode in modes:
                R[("trans", mode)] = futs[mode].result()
        for mode in modes:
            for k, v in R[("trans", mode)][1].items():
                log(f"     {mode:8s} {k:14s} {v['status']} ({v['how']}; {v['s']}s)")
            log(f"  {mode}: {R[('trans', mode)][0]}")
            for k, v in R[("trans", mode)][1].items():
                if v.get("cex"):
                    c = v["cex"]
                    log(f"   {k}: confirmed on emul_matrix: {c['confirmed_on_code']}; fails at (A, C): {c['fails']}")
                    for nm in "ABC":
                        log(f"        {nm} {fmt_shape(c[nm])}")
        log("\n== the joined host dominates every model")
        for mode in modes:
            R[("join", mode)] = join_dominance(model, mode, M, timeout_ms, 20000)
            log(f"  {mode:8s}: {R[('join', mode)][0]}")
            for k, (s, d) in R[("join", mode)][1].items():
                if s != "PROVED":
                    log(f"     {k}: {s} {d if not (d and 'target' in d) else fmt_shape(d['target'])}")
        log("\n== bounded exhaustive transitivity (real code) on synthetic families")
        R["box"] = {name: box_transitivity(space, name, modes, box_n, log=log) for name in ("heads", "heads_eq", "rec")}
    if not skip_real:
        log("\n== real-data transitivity violations, mode monotonicity")
        R["real_trans"] = real_transitivity(space, P, modes, log=log)
        R["real_mono"] = real_monotone(P, log=log)
    if edges:
        log("\n== edge justification")
        rows = E.edge_rows(space, P)
        R["space"] = space
        gaps, exs = E.write(rows, edges, len(P), props=None if skip_proofs else props_markdown(R))
        R["edges"] = (rows, gaps, exs)
        log(f"  wrote {edges}: {len(rows)} rules, {len(gaps)} headline gaps, {len(exs)} exact-slice approximate")
        for r in gaps:
            log(f"     GAP {r['just'].verdict:11s} {r['rule']}  (payable real edges {r['used']['payable']:,})")
    log(f"\ndone in {time.time() - t0:.0f}s; differential disagreements: {R['disagreements']}")
    return R


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--mode", default="all", help="exact | payable | mixgap | capacity | all (comma-separated)")
    ap.add_argument("--timeout", type=int, default=60, help="seconds per solver call")
    ap.add_argument("--examples", type=int, default=150, help="Hypothesis lists per flag set")
    ap.add_argument("--skip-hypothesis", action="store_true")
    ap.add_argument("--skip-real", action="store_true")
    ap.add_argument("--skip-proofs", action="store_true")
    ap.add_argument("--edges", nargs="?", const="verify/EDGE_JUSTIFICATION.md", default=None,
                    help="write the edge justification table (default path verify/EDGE_JUSTIFICATION.md)")
    a = ap.parse_args(argv)
    modes = MODES if a.mode == "all" else tuple(a.mode.split(","))
    R = run(modes, a.timeout * 1000, a.examples, a.skip_hypothesis, a.skip_real,
            a.edges or ("verify/EDGE_JUSTIFICATION.md" if a.mode == "all" else None), skip_proofs=a.skip_proofs)
    return 1 if R["disagreements"] else 0


