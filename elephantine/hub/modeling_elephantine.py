def uconfig_of(config) -> UConfig:
    """The host's UConfig from an ElephantineConfig (unknown keys are an error, not ignored)."""
    names = {f.name for f in fields(UConfig)}
    host = dict(config.host)
    extra = set(host) - names
    if extra:
        raise ValueError(f"host keys this architecture does not have: {sorted(extra)}")
    if "engram_orders" in host:
        host["engram_orders"] = tuple(host["engram_orders"])
    return UConfig(**host)


class ElephantineForCausalLM(PreTrainedModel, GenerationMixin):
    """UniversalElephantine behind the transformers API. `causal` (config default; overridable per
    call) picks the causal or the full (diffusion) mask. Logits are float64."""
    config_class = ElephantineConfig
    base_model_prefix = "model"
    main_input_name = "input_ids"
    # tensors left at the architecture's default are not stored: they keep the value __init__ gives
    _keys_to_ignore_on_load_missing = [r".*"]
    _supports_cache_class = False
    _is_stateful = True                                 # no KV cache: never build one

    def __init__(self, config: ElephantineConfig):
        super().__init__(config)
        self.model = UniversalElephantine(uconfig_of(config))
        self.post_init()

    @classmethod
    def get_init_context(cls, *args, **kwargs):
        # build on CPU with the architecture's own init (no meta device), so a tensor the weights file
        # leaves out keeps its default value instead of uninitialised memory
        return [no_init_weights()]

    def _init_weights(self, module):
        pass                                            # the defaults are UniversalElephantine's own

    def get_input_embeddings(self):
        return self.model.embed

    def set_input_embeddings(self, value):
        self.model.embed = value

    def forward(self, input_ids=None, attention_mask=None, labels=None, causal=None, return_dict=None, **kwargs):
        if attention_mask is not None and not bool((attention_mask == 1).all()):
            raise ValueError("padding masks are not supported: pass unpadded sequences of equal length")
        causal = self.config.causal if causal is None else bool(causal)
        logits = self.model(input_ids, causal=causal)
        loss = None
        if labels is not None:
            lg, lb = (logits[:, :-1], labels[:, 1:]) if causal else (logits, labels)
            loss = F.cross_entropy(lg.reshape(-1, lg.shape[-1]), lb.reshape(-1), ignore_index=-100)
        return CausalLMOutput(loss=loss, logits=logits)

    def prepare_inputs_for_generation(self, input_ids, **kwargs):
        return {"input_ids": input_ids}

    def _supports_default_dynamic_cache(self):
        return False
