class Page:
    """A fresh browser context on the page, collecting console errors and uncaught exceptions."""

    def __init__(self, browser, zoo, hash_="", viewport=DESKTOP, scheme="light", mobile=False):
        self.ctx = browser.new_context(viewport=viewport, color_scheme=scheme, is_mobile=mobile, has_touch=mobile,
                                       device_scale_factor=2 if mobile else 1)
        self.ctx.set_default_timeout(120_000)                    # a loaded machine renders slowly
        self.pg = self.ctx.new_page()
        self.errors = []
        self.pg.on("console", lambda m: m.type in ("error", "warning") and self.errors.append(f"{m.type}: {m.text}"))
        self.pg.on("pageerror", lambda e: self.errors.append(f"pageerror: {e}"))
        self.zoo = zoo
        self.pg.goto(zoo.url + hash_)
        self.pg.wait_for_selector("#stats .stat")

    def close(self):
        errors = self.errors
        self.ctx.close()
        assert not errors, errors

    def text(self):
        return self.pg.evaluate("document.body.innerText")

    def assert_clean_text(self, where=""):
        t = self.text()
        bad = [t[max(0, m.start() - 80):m.end() + 20] for m in BAD_TEXT.finditer(t)]
        assert not bad, (where, bad)

    def hash(self):
        return self.pg.evaluate("location.hash")

    def visible_nodes(self):
        return set(self.pg.evaluate("""[...document.querySelectorAll('#svg g.node')]
            .filter(g => g.style.display !== 'none').map(g => +g.dataset.i)"""))

    def table_rows(self):
        return self.pg.evaluate("[...document.querySelectorAll('#tbl tbody tr')].map(tr => +tr.dataset.i)")

    def panel(self):
        return self.pg.evaluate(PANEL_JS)

    def goto_hash(self, h):
        self.pg.evaluate("h => { location.hash = h; }", h)


